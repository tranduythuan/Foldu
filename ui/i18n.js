let LANG = 'vi';

/** Đổi ngôn ngữ đang dùng cho giao diện */
function setLang(code) {
  LANG = DICT[code] ? code : 'vi';
  document.documentElement.lang = LANG;
}

function currentLang() {
  return LANG;
}

/** Tra chuỗi, thay {0} {1}... bằng tham số */
function t(key, ...args) {
  const s = (DICT[LANG] && DICT[LANG][key]) || (DICT.vi && DICT.vi[key]) || key;
  return args.length ? s.replace(/\{(\d+)\}/g, (m, i) => (args[i] !== undefined ? args[i] : m)) : s;
}

/**
 * Áp từ điển lên mọi phần tử có đánh dấu:
 *   data-i18n       -> nội dung chữ
 *   data-i18n-html  -> nội dung có thẻ HTML
 *   data-i18n-ph    -> thuộc tính placeholder
 *   data-i18n-title -> thuộc tính title
 */
function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}
